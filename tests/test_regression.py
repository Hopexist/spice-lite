"""Results of Milestones 1-6 must not change when later work lands.

`golden_m1_m6.json` was generated by running the v0.6 tag's own source (`git archive`, not the
working tree) over every example that existed then: op, dc sweep, ac and tran, each summarised as
[first, last, min, max, mean] per signal (complex AC signals: magnitude and unwrapped phase).
"""
import json
from pathlib import Path

import numpy as np
import pytest

from spicelite import parse
from spicelite.analysis.ac import ac
from spicelite.analysis.dc import dc_sweep, op
from spicelite.analysis.tran import tran

HERE = Path(__file__).parent
GOLDEN = json.loads((HERE / "golden_m1_m6.json").read_text())
GOLDEN_M7 = json.loads((HERE / "golden_m1_m7.json").read_text())  # every example that existed at the end of M7


def stats(x) -> list:
    x = np.asarray(x)
    if np.iscomplexobj(x):
        return [stats(np.abs(x)), stats(np.unwrap(np.angle(x)))]
    return [float(x[0]), float(x[-1]), float(x.min()), float(x.max()), float(x.mean())]


def check(got: dict, want: dict, what: str) -> None:
    assert got.keys() == want.keys(), f"{what}: signals changed"
    for name in want:
        # 1e-9 relative with a tiny absolute floor for signals that are zero or nearly so: the
        # algorithms are unchanged, so agreement is really ~1e-14; this just allows BLAS differences.
        # arrays, because complex AC signals summarise to a nested [magnitude stats, phase stats]
        assert np.asarray(got[name]) == pytest.approx(np.asarray(want[name]), rel=1e-9, abs=1e-12), f"{what} {name}"


@pytest.mark.parametrize("name", sorted(GOLDEN))
def test_results_match_the_v06_golden_values(name):
    check_example(name, GOLDEN[name])


@pytest.mark.parametrize("name", sorted(GOLDEN_M7))
def test_results_match_the_m7_golden_values(name):
    """Frozen from the M7 source (commit 35ecdb5, before MOSFETs): adding M8/M9 must not move any of
    the 26 earlier examples, including the controlled-source ones the v0.6 file predates."""
    check_example(name, GOLDEN_M7[name])


def check_example(name, want):
    c = parse((HERE.parent / "examples" / name).read_text())
    r = op(c)
    check(r.voltages, want["op"]["v"], f"{name} op voltages")
    check(r.currents, want["op"]["i"], f"{name} op currents")
    if "dc" in want:
        d = dc_sweep(c)
        check({k: stats(v) for k, v in d.voltages.items()}, want["dc"]["v"], f"{name} dc voltages")
        check({k: stats(v) for k, v in d.currents.items()}, want["dc"]["i"], f"{name} dc currents")
    if "ac" in want:
        a = ac(c)
        check({k: stats(v) for k, v in a.voltages.items()}, want["ac"]["v"], f"{name} ac voltages")
        check({k: stats(v) for k, v in a.currents.items()}, want["ac"]["i"], f"{name} ac currents")
    if "tran" in want:
        t = tran(c)
        check({k: stats(v) for k, v in t.voltages.items()}, want["tran"]["v"], f"{name} tran voltages")
        check({k: stats(v) for k, v in t.currents.items()}, want["tran"]["i"], f"{name} tran currents")


