"""Regenerate docs/convergence.md: transient error vs step size for backward Euler and trapezoidal.

Same circuit and exact answer as tests/test_tran.py::test_convergence_order_halving_h (RC, tau = 1 ms, source ramps
0 -> 1 V over 0.5 ms), plus the ideal-step case of test_trapezoidal_stays_second_order_for_an_ideal_step.

    python scripts/convergence_table.py          # writes docs/convergence.md
"""
from __future__ import annotations

import warnings
from pathlib import Path

import numpy as np

from spicelite import parse
from spicelite.analysis.tran import ResolutionWarning, tran

TAU = 1e-3  # R C = 1 kohm * 1 uF
TR = 0.5e-3  # ramp time of the source
KS = range(2, 8)  # h = TR / 4 ... TR / 128


def ramp_step(t: np.ndarray) -> np.ndarray:
    """Exact response of tau y' + y = u to a 0 -> 1 ramp over TR, then 1."""
    y = lambda x: (x - TAU * (1 - np.exp(-x / TAU))) / TR  # noqa: E731
    return np.where(t <= TR, y(np.minimum(t, TR)), 1 + (y(TR) - 1) * np.exp(-(t - TR) / TAU))


def max_error(method: str, h: float, ideal: bool) -> float:
    source = "PULSE(0 1 0 0 0 1 10)" if ideal else f"PULSE(0 1 0 {TR!r} 1m 1 10)"
    net = f"t\nV1 in 0 {source}\nR1 in out 1k\nC1 out 0 1u\n.tran {h!r} 4e-3\n.end"
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", ResolutionWarning)  # an ideal step is deliberately under-resolved
        r = tran(parse(net), method=method)
    exact = 1 - np.exp(-r.time / TAU) if ideal else ramp_step(r.time)
    return float(np.abs(r.voltages["out"] - exact).max())


def table(ideal: bool) -> list[str]:
    rows = ["| h (s) | h / tau | backward Euler error | ratio | trapezoidal error | ratio |",
            "|---:|---:|---:|---:|---:|---:|"]
    prev: tuple[float, float] | None = None
    for k in KS:
        h = TR / 2**k
        be, trap = max_error("be", h, ideal), max_error("trap", h, ideal)
        ratios = ("", "") if prev is None else (f"{prev[0] / be:.2f}", f"{prev[1] / trap:.2f}")
        rows.append(f"| {h:.4g} | {h / TAU:.4g} | {be:.3e} | {ratios[0]} | {trap:.3e} | {ratios[1]} |")
        prev = (be, trap)
    return rows


def main() -> None:
    out = [
        "# Transient convergence: backward Euler vs trapezoidal",
        "",
        "Generated by `scripts/convergence_table.py` from the solver itself. Circuit: R = 1 kohm, C = 1 uF (tau = 1 ms), "
        "`.tran h 4m`. Error is the maximum absolute difference to the exact response over all time points. "
        "The ratio is the error at the previous (twice as large) step divided by this one: about 2 means first order, "
        "about 4 means second order. `tests/test_tran.py` asserts these ratios (2 +/- 0.15 and 4 +/- 0.2).",
        "",
        "## Source ramps 0 -> 1 V over 0.5 ms",
        "",
        *table(ideal=False),
        "",
        "## Ideal step (rise time 0) at t = 0",
        "",
        *table(ideal=True),
        "",
    ]
    path = Path(__file__).resolve().parent.parent / "docs" / "convergence.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print(path)


if __name__ == "__main__":
    main()
